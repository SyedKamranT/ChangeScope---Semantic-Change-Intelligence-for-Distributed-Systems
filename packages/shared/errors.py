"""Shared API Error Conventions adhering to RFC 7807 Problem Details for HTTP APIs."""

from typing import Any

from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field


class ProblemDetail(BaseModel):
    """RFC 7807 Problem Details Model."""

    type: str = Field(default="about:blank", description="URI reference identifying problem type.")
    title: str = Field(description="Short human-readable summary of problem.")
    status: int = Field(description="HTTP status code generated by origin server.")
    detail: str = Field(description="Human-readable explanation specific to this occurrence.")
    instance: str | None = Field(default=None, description="URI reference identifying specific occurrence.")
    request_id: str | None = Field(default=None, description="Correlation request ID.")
    invalid_params: list[dict[str, Any]] | None = Field(
        default=None, description="Detailed parameter or validation errors."
    )


class ChangeScopeBaseError(Exception):
    """Root domain exception for ChangeScope."""

    status_code: int = 500
    error_type: str = "https://changescope.io/errors/internal-server-error"
    title: str = "Internal Server Error"

    def __init__(
        self,
        message: str,
        invalid_params: list[dict[str, Any]] | None = None,
        status_code: int | None = None,
        error_type: str | None = None,
        title: str | None = None,
    ):
        super().__init__(message)
        self.message = message
        self.invalid_params = invalid_params or []
        if status_code is not None:
            self.status_code = status_code
        if error_type is not None:
            self.error_type = error_type
        if title is not None:
            self.title = title


